ROOT = "docs/design/assets/"
LAB_RO = ("Только чтение · Лаборатория 7.4", "#eef4ff", "#3156a3", 270)
X0, X1 = 48, 1552  # content edges of top-level sections


def write(svg, path, active, mode=LAB_RO, breadcrumb=None, chips=()):
    svg = appbar.apply(svg, active=active, mode=mode, depth_prefix="../../../../",
                       breadcrumb=breadcrumb, chips=chips)
    os.makedirs(os.path.dirname(ROOT + path), exist_ok=True)
    with open(ROOT + path, "w", encoding="utf-8", newline="") as f:
        f.write(svg)
    print("written", ROOT + path)


def page_title(title, subtitle, y=124):
    return t(X0, y, title, "title") + t(X0, y + 28, subtitle, "small muted")


def tabs(x, y, items):
    """Underlined tabs: (label, width, selected)."""
    s = ""
    for label, w, sel in items:
        if sel:
            s += t(x, y, label, "body", "#1d3f86", weight="700")
            s += f'  <rect x="{x}" y="{y + 10}" width="{w}" height="3" rx="1.5" fill="#3156a3"/>\n'
        else:
            s += t(x, y, label, "body", "#475467", weight="500")
        x += w + 28
    return s + f'  <line x1="{X0}" y1="{y + 13}" x2="{X1}" y2="{y + 13}" stroke="#e4e7ec"/>\n'


def pills(x, y, items):
    for label, w, on in items:
        if on:
            yield box(x, y, w, 32, fill="#243746", stroke="#243746", rx=16) + t(x + w / 2, y + 21, label, "small", "#ffffff", "middle", "650")
        else:
            yield box(x, y, w, 32, stroke="#c9d3ea", rx=16) + t(x + w / 2, y + 21, label, "small", None, "middle", "600")
        x += w + 8


def search(x, y, w, text):
    return box(x, y, w, 38, stroke="#7a8d9b", rx=8) + icon("search", x + 12, y + 9, "#667085", 20) + t(x + 42, y + 24, text, "small muted")


def table_head(x, y, w, cols):
    s = box(x, y, w, 34, fill="#f8fafc", stroke="#eef0f4", rx=6)
    for cx, label in cols:
        s += t(cx, y + 22, label, "xs muted", weight="700")
    return s


def row_line(x, y, w):
    return f'  <line x1="{x}" y1="{y}" x2="{x + w}" y2="{y}" stroke="#eef0f4"/>\n'


def kv(x, y, k, v, kx=None, cls="small", weight="600"):
    return t(x, y, k, "small muted") + t(kx or x + 150, y, v, cls, weight=weight)


def wrap(x, y, lines, cls="small muted", fill=None, step=22):
    return "".join(t(x, y + i * step, line, cls, fill) for i, line in enumerate(lines))


